def _is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def _is_int(v):
    return isinstance(v, int) and not isinstance(v, bool)


def _is_point(p):
    return isinstance(p, list) and len(p) == 2 and _is_num(p[0]) and _is_num(p[1])


def _enum_ok(obj, key, allowed, tag, problems):
    if key in obj and obj[key] not in allowed:
        problems.append(
            "%s bad enum %s=%r (allowed: %s)" % (tag, key, obj[key], ", ".join(allowed))
        )


def _num_ok(obj, key, tag, problems, lo=None, hi=None):
    if key not in obj:
        return
    v = obj[key]
    if not _is_num(v):
        problems.append("%s %s must be a number (found %r)" % (tag, key, v))
    elif lo is not None and not lo <= v <= hi:
        problems.append("%s %s must be between %s and %s (found %s)" % (tag, key, lo, hi, v))


def _int_ok(obj, key, tag, problems):
    if key in obj and not _is_int(obj[key]):
        problems.append("%s %s must be an integer (found %r)" % (tag, key, obj[key]))


def _bool_ok(obj, key, tag, problems):
    if key in obj and not isinstance(obj[key], bool):
        problems.append("%s %s must be true or false (found %r)" % (tag, key, obj[key]))


def _hex_ok(obj, key, tag, problems):
    if key in obj and not (isinstance(obj[key], str) and HEX_RE.match(obj[key])):
        problems.append("%s %s must be a colour like #rrggbb (found %r)" % (tag, key, obj[key]))


def _points_ok(points, tag, problems, minimum):
    if not isinstance(points, list) or len(points) < minimum:
        problems.append("%s must be a list of at least %d [x,y] points" % (tag, minimum))
        return False
    for j, p in enumerate(points):
        if not _is_point(p):
            problems.append("%s point %d must be [x,y] numbers (found %r)" % (tag, j, p))
            return False
    return True


def _check_part(i, part, problems):
    """Check one entry of parts; return its kind if it is a known kind, else None."""
    base = "parts[%d]" % i
    if not isinstance(part, dict):
        problems.append("%s is not an object" % base)
        return None
    if "kind" not in part:
        problems.append("%s missing kind" % base)
        return None
    kind = part["kind"]
    if not isinstance(kind, str) or kind not in KINDS:
        problems.append("%s unknown kind %r" % (base, kind))
        return None
    spec = KINDS[kind]
    tag = "%s %s" % (base, kind)
    for field in spec["req"]:
        if field not in part:
            problems.append("%s missing required field %s" % (tag, field))
    for key, value in part.items():
        if key in ("kind", "note"):
            continue
        if key in spec["enums"]:
            _enum_ok(part, key, spec["enums"][key], tag, problems)
        elif key == "side":
            if value not in SIDES:
                problems.append(
                    "%s side %r not allowed (use both, near, far or centre)" % (tag, value)
                )
        elif key in BOOLS:
            _bool_ok(part, key, tag, problems)
        elif key in INTS:
            _int_ok(part, key, tag, problems)
            if key == "overriders" and _is_int(value) and not 0 <= value <= 4:
                problems.append("%s overriders must be between 0 and 4 (found %s)" % (tag, value))
        elif key == "across_x":
            if value is not None and not _is_num(value):
                problems.append("%s across_x must be a number or null (found %r)" % (tag, value))
        elif key in NUMERIC:
            if not _is_num(value):
                problems.append("%s %s must be a number (found %r)" % (tag, key, value))
        elif key == "path":
            _points_ok(value, "%s path" % tag, problems, 2)
    return kind


def validate(details, dossier=None, strict=False):
    """Return a list of problem strings; an empty list means the details pass."""
    problems = []
    if not isinstance(details, dict):
        return ["top level value is not an object"]

    ver = details.get("version")
    if not (_is_int(ver) and ver == 2):
        problems.append("version must be 2 (found %r)" % (ver,))
    car_id = details.get("id")
    if not isinstance(car_id, str) or not car_id:
        problems.append("id must be a non-empty string")
    if "belt_y" in details and not _is_num(details["belt_y"]):
        problems.append("belt_y must be a number (found %r)" % (details["belt_y"],))
    _enum_ok(details, "window_frame", FRAMES, "top level", problems)

    car = details.get("caricature")
    if car is not None:
        if not isinstance(car, dict):
            problems.append("caricature must be an object")
        else:
            for key in car:
                if key not in CARICATURE_KEYS:
                    problems.append("caricature has unknown key %s" % key)
                else:
                    _num_ok(car, key, "caricature", problems, 0.8, 1.4)

    wheel = details.get("wheel")
    if wheel is not None:
        if not isinstance(wheel, dict):
            problems.append("wheel must be an object")
        else:
            _enum_ok(wheel, "style", WHEEL_STYLES, "wheel", problems)
            _enum_ok(wheel, "hub", WHEEL_HUBS, "wheel", problems)
            _bool_ok(wheel, "whitewall", "wheel", problems)
            _bool_ok(wheel, "trim_ring", "wheel", problems)
            _num_ok(wheel, "hubcap_r", "wheel", problems)
            _int_ok(wheel, "spokes", "wheel", problems)

    roof = details.get("roof", {})
    if not isinstance(roof, dict):
        problems.append("roof must be an object")
        roof = {}
    _enum_ok(roof, "variant", ROOF_VARIANTS, "roof", problems)
    _hex_ok(roof, "colour", "roof", problems)
    _num_ok(roof, "fold_x0", "roof", problems)
    _num_ok(roof, "fold_x1", "roof", problems)
    variant = roof.get("variant", "hard")

    paint = details.get("paint", {})
    if not isinstance(paint, dict):
        problems.append("paint must be an object")
        paint = {}
    _hex_ok(paint, "colour2", "paint", problems)
    _enum_ok(paint, "finish", ("solid", "metallic"), "paint", problems)
    zones = paint.get("zones", [])
    if not isinstance(zones, list):
        problems.append("paint.zones must be a list")
        zones = []
    for j, zone in enumerate(zones):
        tag = "paint.zones[%d]" % j
        if not isinstance(zone, dict):
            problems.append("%s is not an object" % tag)
            continue
        _enum_ok(zone, "region", ZONE_REGIONS, tag, problems)
        _enum_ok(zone, "use", ZONE_USES, tag, problems)
        for key in ("y", "y2", "x0", "x1", "w"):
            _num_ok(zone, key, tag, problems)
        if zone.get("use") == "paint2" and "colour2" not in paint:
            problems.append("%s uses paint2 but paint.colour2 is not set" % tag)

    windows = details.get("windows", [])
    if not isinstance(windows, list):
        problems.append("windows must be a list of polygons")
        windows = []
    for j, poly in enumerate(windows):
        _points_ok(poly, "windows[%d]" % j, problems, 3)

    pillars = details.get("pillars", [])
    if not isinstance(pillars, list):
        problems.append("pillars must be a list")
        pillars = []
    for j, pillar in enumerate(pillars):
        tag = "pillars[%d]" % j
        if not isinstance(pillar, dict):
            problems.append("%s is not an object" % tag)
            continue
        _points_ok(pillar.get("poly"), "%s poly" % tag, problems, 2)
        _num_ok(pillar, "lat_from", tag, problems, 0, 1)

    cockpit = details.get("cockpit")
    if cockpit is not None:
        if not isinstance(cockpit, dict):
            problems.append("cockpit must be an object")
        else:
            for key in ("x0", "x1", "floor_y"):
                _num_ok(cockpit, key, "cockpit", problems)
            _hex_ok(cockpit, "seat", "cockpit", problems)
            _hex_ok(cockpit, "dash", "cockpit", problems)
            if variant != "open":
                problems.append("cockpit applies to open cars only (roof.variant is %r)" % variant)

    parts = details.get("parts")
    if not isinstance(parts, list):
        problems.append("parts must be a list")
        parts = []
    counts = {}
    for i, part in enumerate(parts):
        kind = _check_part(i, part, problems)
        if kind is not None:
            counts[kind] = counts.get(kind, 0) + 1

    if dossier is not None:
        problems.extend(_dossier_problems(parts, details, dossier))

    if strict:
        problems.extend(_strict_problems(parts, details, dossier, counts, windows, variant))
    return problems


def _dossier_problems(parts, details, dossier):
    """Checks that need the dossier's dims_mm, plan and doors."""
    out = []
    dims = dossier.get("dims_mm")
    if not isinstance(dims, dict):
        return ["dossier has no dims_mm object"]
    length = dims.get("length")
    height = dims.get("height")
    if not (_is_num(length) and _is_num(height) and length > 0):
        return ["dossier dims_mm needs numeric length and height"]
    hu = height / length * 100.0
    plan = dossier.get("plan")
    width_units = plan.get("width_units") if isinstance(plan, dict) else None
    half_w = width_units / 2.0 + 1.0 if _is_num(width_units) else None

    def in_box(points, tag):
        for p in points:
            if not (-51 <= p[0] <= 51 and 0 <= p[1] <= hu + 1):
                out.append(
                    "%s point %s is outside x -51..51 or y 0..%.2f (height units + 1)"
                    % (tag, p, hu + 1)
                )
                return

    for i, part in enumerate(parts):
        if not isinstance(part, dict):
            continue
        tag = "parts[%d] %s" % (i, part.get("kind"))
        for key in ("x", "x2"):
            if _is_num(part.get(key)) and not -51 <= part[key] <= 51:
                out.append("%s %s=%s is outside -51..51" % (tag, key, part[key]))
        if _is_num(part.get("y")) and not 0 <= part["y"] <= hu + 1:
            out.append("%s y=%s is outside 0..%.2f" % (tag, part["y"], hu + 1))
        if _is_num(part.get("lat")) and half_w is not None and abs(part["lat"]) > half_w:
            out.append(
                "%s lat=%s is more than plan.width_units/2+1 (%.2f)"
                % (tag, part["lat"], half_w)
            )
        if part.get("kind") in ("bumper", "plate", "grille") and "end" in part:
            x = part.get("x")
            if _is_num(x):
                if part["end"] == "front" and x < 40:
                    out.append("%s front end needs x >= 40 (found %s)" % (tag, x))
                if part["end"] == "rear" and x > -40:
                    out.append("%s rear end needs x <= -40 (found %s)" % (tag, x))
        if part.get("kind") == "shutline" and isinstance(part.get("path"), list):
            if all(_is_point(p) for p in part["path"]):
                in_box(part["path"], tag + " path")

    belt = details.get("belt_y")
    if _is_num(belt) and not 0.35 * hu <= belt <= 0.95 * hu:
        out.append(
            "belt_y %s must be between 0.35 and 0.95 of height units (%.2f to %.2f)"
            % (belt, 0.35 * hu, 0.95 * hu)
        )
    windows = details.get("windows")
    if isinstance(windows, list):
        for j, poly in enumerate(windows):
            if isinstance(poly, list) and all(_is_point(p) for p in poly):
                in_box(poly, "windows[%d]" % j)
    return out


def _strict_problems(parts, details, dossier, counts, windows, variant):
    out = []
    if len(parts) < 24:
        out.append("strict: needs at least 24 parts (found %d)" % len(parts))
    if counts.get("headlamp", 0) < 1:
        out.append("strict: needs at least 1 headlamp")
    if counts.get("taillamp", 0) < 1:
        out.append("strict: needs at least 1 taillamp")
    for kind in ("bumper", "plate"):
        ends = set(
            p.get("end") for p in parts
            if isinstance(p, dict) and p.get("kind") == kind and isinstance(p.get("end"), str)
        )
        for end in ("front", "rear"):
            if end not in ends:
                out.append("strict: needs a %s %s" % (end, kind))
    if counts.get("exhaust", 0) < 1:
        out.append("strict: needs at least 1 exhaust")
    if "wheel" not in details:
        out.append("strict: needs a wheel object")
    if "belt_y" not in details:
        out.append("strict: needs belt_y")
    detail_count = sum(counts.get(k, 0) for k in ("badge", "handle", "strip", "crease", "shutline"))
    if detail_count < 3:
        out.append(
            "strict: needs at least 3 badge/handle/strip/crease/shutline parts (found %d)"
            % detail_count
        )
    if dossier is not None and variant != "open":
        doors = dossier.get("doors")
        if _is_int(doors) and counts.get("shutline", 0) < 2 * doors + 2:
            out.append(
                "strict: needs at least %d shutline parts for %d doors (found %d)"
                % (2 * doors + 2, doors, counts.get("shutline", 0))
            )
    if variant not in ("open", "soft_down") and len(windows) < 2:
        out.append("strict: windows needs at least 2 polygons (found %d)" % len(windows))
    return out


def _read_json(path):
    try:
        with open(path, "rb") as f:
            raw = f.read()
    except OSError as e:
        raise ValueError("cannot read file: %s" % e.strerror)
    try:
        return json.loads(raw.decode("utf-8"))
    except (UnicodeDecodeError, ValueError) as e:
        raise ValueError("not valid JSON: %s" % e)


def load(path):
    """Load one details file; raises ValueError if it is unreadable or not an object."""
    data = _read_json(path)
    if not isinstance(data, dict):
        raise ValueError("top level value is not an object")
    return data


def _fmt(v):
    if v is True:
        return "true"
    if v is False:
        return "false"
    if v is None:
        return "null"
    return str(v)


